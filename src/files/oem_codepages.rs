pub(super) struct SingleByteCodePage {
    decode: &'static [char; 128],
    best_fit: &'static [(u16, u8)],
}

pub(super) fn for_codepage(codepage: u32) -> Option<SingleByteCodePage> {
    match codepage {
        720 => Some(SingleByteCodePage { decode: DECODE_720, best_fit: BEST_FIT_720 }),
        858 => Some(SingleByteCodePage { decode: DECODE_858, best_fit: BEST_FIT_858 }),
        _ => None,
    }
}

impl SingleByteCodePage {
    pub(super) fn decode(&self, bytes: &[u8]) -> String {
        bytes.iter().map(|&byte| {
            if byte.is_ascii() {
                char::from(byte)
            } else {
                self.decode[usize::from(byte) - 128]
            }
        }).collect()
    }

    pub(super) fn encode(&self, text: &str) -> Vec<u8> {
        text.encode_utf16().map(|unit| {
            if let Ok(byte) = u8::try_from(unit) {
                if byte.is_ascii() {
                    return byte;
                }
            }
            if let Some((byte, _)) = (128u8..=255).zip(self.decode.iter())
                .find(|(_, mapped)| u32::from(**mapped) == u32::from(unit))
            {
                return byte;
            }
            match self.best_fit.binary_search_by_key(&unit, |entry| entry.0) {
                Ok(index) => self.best_fit[index].1,
                Err(_) => b'?',
            }
        }).collect()
    }
}

